const WORLD_REGION_ALIAS_MAP = {
  ...Object.entries(WORLD_NAME_MAP).reduce<Record<string, string>>(
    (map, [regionName, displayName]) => {
      map[displayName] = regionName;
      return map;
    },
    {},
  ),
  China: '中国',
  中国: '中国',
  白俄: 'Belarus',
  香港: '中国',
  中国香港: '中国',
};

export function getWorldCountryDisplayName(name: string, fallback = name) {
  if (!name) return fallback;
  return WORLD_NAME_MAP[name] || fallback;
}

export function normalizeWorldRegionName(name: string, availableRegionNames?: ReadonlySet<string>) {
  const rawName = String(name || '').trim();
  if (!rawName) return '';

  const aliasName = WORLD_REGION_ALIAS_MAP[rawName] || rawName;
  const candidates = [rawName, aliasName].filter(Boolean);

  if (availableRegionNames) {
    return candidates.find((item) => availableRegionNames.has(item)) || aliasName;
  }

  return aliasName;
}
