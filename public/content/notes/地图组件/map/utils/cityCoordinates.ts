/**
 * 根据省份名称获取中心坐标（基于省会城市）
 *
 * @param provinceName - 省份名称（如：'安徽省'、'安徽'）
 * @returns 返回经纬度坐标数组 [经度, 纬度]，如果省份不存在则返回中国中心点坐标
 */
export const getProvinceCenter = (provinceName: string): [number, number] => {
  if (provinceCenterMap[provinceName]) {
    return provinceCenterMap[provinceName];
  }
  const normalized = provinceName
    .replace('省', '')
    .replace('市', '')
    .replace('自治区', '')
    .replace('特别行政区', '');
  return provinceCenterMap[normalized] || [104.195, 35.861];
};

